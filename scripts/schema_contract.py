"""Build the public content row schema; matching definitions are private."""
import copy
import json
from pathlib import Path
ROOT = Path(__file__).resolve().parent.parent

def row_schema(authoring=None):
    schema = copy.deepcopy(authoring or json.loads((ROOT / "schemas/grammar-yaml.schema.json").read_text()))
    schema["$id"] = "https://manabi.io/schemas/grammar-table-row.schema.json"
    schema["title"] = "Manabi Grammar Content Row (generated by schema_contract.py)"
    schema["required"] += ["targetLanguage", "headword", "variant", "info"]
    schema["properties"]["info"] = {"$ref": "#/$defs/info"}
    schema["properties"]["referenceBindings"] = {"type": "array", "items": {"$ref": "#/$defs/referenceBinding"}}
    return schema

def check_row_schema():
    if json.loads((ROOT / "schemas/grammar-table-row.schema.json").read_text()) != row_schema():
        raise ValueError("Row schema is stale; run python scripts/schema_contract.py --write")

if __name__ == "__main__":
    import sys
    if sys.argv[1:] == ["--write"]:
        path = ROOT / "schemas/grammar-table-row.schema.json"
        if path.resolve() != path: raise ValueError("Unexpected schema target")
        path.write_text(json.dumps(row_schema(), ensure_ascii=False, indent=2) + "\n")
    elif not sys.argv[1:]: check_row_schema()
    else: raise SystemExit("Usage: python scripts/schema_contract.py [--write]")
